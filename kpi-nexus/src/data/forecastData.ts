// Source: kpi_trend_seasonality_prophet.csv
// Columns per row: date, domain, kpi, actual, trend, yhat, yhat_lower, yhat_upper,
//                  is_anomaly, anomaly_score, in_sample, is_future
//
// Each record: { date, actual, trend, yhat, lower, upper, isAnomaly, anomalyScore }

export interface ForecastPoint {
  date: string;       // 'YYYY-MM'
  actual: number | null;
  trend: number;
  yhat: number;
  lower: number;
  upper: number;
  isAnomaly: boolean;
  anomalyScore: number;
}

export interface ForecastSeries {
  domain: string;
  kpi: string;
  label: string;
  unit: string;
  color: string;
  targetColor: string;
  data: ForecastPoint[];
}

// ── helpers ──────────────────────────────────────────────────────────────────
const p = (d: string, a: number | null, tr: number, y: number, lo: number, hi: number, ia: boolean, sc: number): ForecastPoint =>
  ({ date: d.slice(0, 7), actual: a, trend: tr, yhat: y, lower: lo, upper: hi, isAnomaly: ia, anomalyScore: sc });

